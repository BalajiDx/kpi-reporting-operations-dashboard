"""
Clean the raw synthetic operations data and write Clean_*.csv plus a Cleaning Log.

Run:  python clean_dataset.py   (after generate_dataset.py)
"""
import os
import shutil
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
RAW, OUT = os.path.join(HERE, "Raw Dataset"), os.path.join(HERE, "Cleaned Dataset")
os.makedirs(OUT, exist_ok=True)
log = []

j = pd.read_csv(os.path.join(RAW, "Jobs.csv"), keep_default_na=False)
n0 = len(j)
j = j.drop_duplicates()
log.append(("Jobs", "Duplicate job rows removed", n0 - len(j)))
fixed = j.Client.str.upper() == j.Client
j.loc[fixed, "Client"] = j.loc[fixed, "Client"].str.title()
log.append(("Jobs", "Client names in capitals set to title case", int(fixed.sum())))
n1 = len(j)
j = j.drop_duplicates(subset="JobID")
log.append(("Jobs", "Duplicates found after fixing client names removed", n1 - len(j)))
# a missing team can be filled from the job type, which belongs to one team only
type_team = j[j.Team != ""].groupby("JobType").Team.agg(lambda s: s.mode()[0])
miss = j.Team == ""
j.loc[miss, "Team"] = j.loc[miss, "JobType"].map(type_team)
log.append(("Jobs", "Missing Team filled from JobType (each job type belongs to one team)", int(miss.sum())))
neg = j.Pages.astype(int) < 0
j["Pages"] = j.Pages.astype(int).abs()
log.append(("Jobs", "Negative Pages (sign error) made positive", int(neg.sum())))
bad = (j.DeliveredDate != "") & (j.DeliveredDate < j.ReceivedDate)
j.loc[bad, ["DeliveredDate", "Status"]] = ["", "Needs review"]
log.append(("Jobs", "DeliveredDate before ReceivedDate: date cleared, Status = 'Needs review' (excluded from delivery KPIs)", int(bad.sum())))
j = j.sort_values("JobID")
j.to_csv(os.path.join(OUT, "Clean_Jobs.csv"), index=False)

for t in ["Staffing", "Escalations"]:
    shutil.copy(os.path.join(RAW, t + ".csv"), os.path.join(OUT, f"Clean_{t}.csv"))
log.append(("Staffing, Escalations", "No issues found (copied as is)", 0))

finals = {f"Clean_{t}": len(pd.read_csv(os.path.join(OUT, f"Clean_{t}.csv"))) for t in ["Jobs", "Staffing", "Escalations"]}
with open(os.path.join(HERE, "Cleaning Log.md"), "w", encoding="utf-8") as fh:
    fh.write("# Data Cleaning Log\n\nGenerated by `clean_dataset.py`. Counts are rows (or values) affected.\n\n")
    fh.write("| Table | Issue / action | Count |\n|---|---|---:|\n")
    for t, a, n in log:
        fh.write(f"| {t} | {a} | {n:,} |\n")
    fh.write("\n## Final row counts\n\n| Table | Rows |\n|---|---:|\n")
    for k, v in finals.items():
        fh.write(f"| {k} | {v:,} |\n")
print(pd.DataFrame(log, columns=["Table", "Action", "Count"]).to_string(index=False))
